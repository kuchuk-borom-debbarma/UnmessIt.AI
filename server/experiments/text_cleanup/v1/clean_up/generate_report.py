import sys
import os
import argparse
from datetime import datetime

def generate_html_report(input_file: str, output_file: str, title: str = "UnmessIt.AI Report"):
    if not os.path.exists(input_file):
        print(f"Error: Input file {input_file} not found.")
        sys.exit(1)
        
    with open(input_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Split by double newline to form paragraphs
    paragraphs = content.split("\n")
    
    html_paragraphs = ""
    for p in paragraphs:
        text = p.strip()
        if text:
            html_paragraphs += f"        <p>{text}</p>\n"

    date_str = datetime.now().strftime("%B %d, %Y - %H:%M:%S")

    html_template = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{title}</title>
    <style>
        :root {{
            --bg-color: #f8fafc;
            --text-color: #1e293b;
            --heading-color: #0f172a;
            --accent-color: #3b82f6;
            --border-color: #e2e8f0;
            --paper-bg: #ffffff;
        }}
        
        body {{
            font-family: 'Inter', -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
            background-color: var(--bg-color);
            color: var(--text-color);
            line-height: 1.6;
            margin: 0;
            padding: 2rem;
            display: flex;
            justify-content: center;
        }}

        .report-container {{
            background-color: var(--paper-bg);
            max-width: 800px;
            width: 100%;
            padding: 3rem 4rem;
            box-shadow: 0 10px 15px -3px rgba(0, 0, 0, 0.1), 0 4px 6px -2px rgba(0, 0, 0, 0.05);
            border-radius: 8px;
        }}

        header {{
            border-bottom: 2px solid var(--border-color);
            padding-bottom: 1.5rem;
            margin-bottom: 2rem;
        }}

        h1 {{
            color: var(--heading-color);
            font-size: 2.25rem;
            margin: 0 0 0.5rem 0;
            font-weight: 700;
        }}

        .meta-info {{
            display: flex;
            justify-content: space-between;
            color: #64748b;
            font-size: 0.875rem;
        }}

        .content p {{
            margin-bottom: 1.25rem;
            font-size: 1.05rem;
            color: #334155;
            text-align: justify;
        }}

        .footer {{
            margin-top: 4rem;
            padding-top: 1.5rem;
            border-top: 1px solid var(--border-color);
            text-align: center;
            font-size: 0.875rem;
            color: #94a3b8;
        }}

        .print-btn {{
            position: fixed;
            bottom: 2rem;
            right: 2rem;
            background-color: var(--accent-color);
            color: white;
            border: none;
            padding: 0.75rem 1.5rem;
            border-radius: 9999px;
            font-weight: 600;
            font-size: 1rem;
            cursor: pointer;
            box-shadow: 0 4px 6px -1px rgba(59, 130, 246, 0.5);
            transition: all 0.2s;
        }}

        .print-btn:hover {{
            background-color: #2563eb;
            transform: translateY(-2px);
            box-shadow: 0 6px 8px -1px rgba(59, 130, 246, 0.6);
        }}

        /* Print-specific styles */
        @media print {{
            body {{
                background-color: white;
                padding: 0;
            }}
            .report-container {{
                box-shadow: none;
                border-radius: 0;
                padding: 0;
                max-width: 100%;
            }}
            .print-btn {{
                display: none;
            }}
            @page {{
                margin: 2cm;
            }}
        }}
    </style>
</head>
<body>
    <div class="report-container">
        <header>
            <h1>{title}</h1>
            <div class="meta-info">
                <span>Generated by UnmessIt.AI</span>
                <span>{date_str}</span>
            </div>
        </header>

        <div class="content">
{html_paragraphs}
        </div>

        <div class="footer">
            <p>Confidential & Proprietary. UnmessIt.AI NLP Pipeline.</p>
        </div>
    </div>
    
    <button class="print-btn" onclick="window.print()">
        🖨️ Print Report
    </button>
</body>
</html>
"""

    with open(output_file, "w", encoding="utf-8") as f:
        f.write(html_template)
    
    print(f"Successfully generated HTML report at: {output_file}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate a print-ready HTML report from text.")
    parser.add_argument("input_file", help="Path to the input text file.")
    parser.add_argument("--output", "-o", default="outputs/report.html", help="Path to the output HTML file.")
    parser.add_argument("--title", "-t", default="UnmessIt.AI Report", help="Title of the report.")
    
    args = parser.parse_args()
    
    generate_html_report(args.input_file, args.output, args.title)
